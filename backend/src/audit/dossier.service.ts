import { AGENT_DEFINITIONS, CONTRACT_VERSION, ORCHESTRATOR_VERSION } from '@trialguard/agents';
import PDFDocument from 'pdfkit';
import { hashObject, sha256Hex } from '../common/canonical-json';
import { notFound } from '../common/errors';
import { ONTOLOGY_VERSION } from '../ontology/dictionary';
import { PrismaService } from '../prisma/prisma.service';
import { RULE_ENGINE_VERSION } from '../rule-engine/evaluator';
